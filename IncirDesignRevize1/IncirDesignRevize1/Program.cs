using IncirDesignRevize1.DATA;
using IncirDesignRevize1.Models;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;

var builder = WebApplication.CreateBuilder(args);

builder.Services.AddSession();


// ???????????????????????????????????????????????????????????????
// 1. VERITABANI BAÐLANTISI (DbContext Kaydý)
// ???????????????????????????????????????????????????????????????
// appsettings.json'dan connection string'i alýp DbContext'e veriyoruz
// AddDbContext = "Bu projenin veritabaný iþlemleri için AppDbContext kullanýlacak" demek
builder.Services.AddDbContext<AppDbContext>(options =>
    options.UseSqlServer(builder.Configuration.GetConnectionString("DefaultConnection")));

// ???????????????????????????????????????????????????????????????
// 2. IDENTITY SERVÝSLERÝNÝN KAYDI
// ???????????????????????????????????????????????????????????????
// AddIdentity = "Bu projede kullanýcý ve rol yönetimi için Identity sistemini kullan" demek
// <AppUser, AppRole> = Hangi sýnýflarý kullanacaðýmýzý belirtiyoruz
builder.Services.AddIdentity<AppUser, AppRole>(options =>
{
    // ?????????????????????????????????????????????????????????
    // ÞÝFRE POLÝTÝKALARI (Password Options)
    // ?????????????????????????????????????????????????????????
    // Kullanýcýlar þifre oluþtururken hangi kurallara uymalý?

    // Þifre en az 6 karakter olmalý
    options.Password.RequiredLength = 6;

    // Þifrede en az 1 rakam olmalý mý? (Örn: sifre123)
    options.Password.RequireDigit = true;

    // Þifrede en az 1 küçük harf olmalý mý? (Örn: sifre)
    options.Password.RequireLowercase = true;

    // Þifrede en az 1 büyük harf olmalý mý? (Örn: Sifre)
    options.Password.RequireUppercase = true;

    // Þifrede en az 1 özel karakter olmalý mý? (Örn: sifre@123)
    // Eðitim amaçlý false yapýyoruz, gerçek projede true olmalý!
    options.Password.RequireNonAlphanumeric = false;

    // Þifrede en az kaç farklý karakter olmalý?
    options.Password.RequiredUniqueChars = 1;

    // ?????????????????????????????????????????????????????????
    // KULLANICI AYARLARI (User Options)
    // ?????????????????????????????????????????????????????????

    // E-posta adresleri benzersiz (unique) olmalý mý?
    // true = Ayný e-posta ile iki hesap açýlamaz
    options.User.RequireUniqueEmail = true;

    // Kullanýcý adýnda hangi karakterler kullanýlabilir?
    // Türkçe karakterler ve boþluk ekliyoruz
    options.User.AllowedUserNameCharacters =
        "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._@+çÇðÐýÝöÖþÞüÜ ";

    // ?????????????????????????????????????????????????????????
    // HESAP KÝLÝTLEME AYARLARI (Lockout Options)
    // ?????????????????????????????????????????????????????????
    // Brute-force saldýrýlarýna karþý koruma

    // Kaç yanlýþ giriþten sonra hesap kilitlensin?
    options.Lockout.MaxFailedAccessAttempts = 5;

    // Hesap ne kadar süre kilitli kalsýn?
    options.Lockout.DefaultLockoutTimeSpan = TimeSpan.FromMinutes(5);

    // Yeni kullanýcýlar için kilitleme aktif mi?
    options.Lockout.AllowedForNewUsers = true;

    // ?????????????????????????????????????????????????????????
    // GÝRÝÞ AYARLARI (SignIn Options)
    // ?????????????????????????????????????????????????????????

    // E-posta doðrulamasý zorunlu mu?
    // false = Kullanýcý hemen giriþ yapabilir
    // true = Önce e-postasýný doðrulamasý gerekir
    options.SignIn.RequireConfirmedEmail = false;

    // Telefon doðrulamasý zorunlu mu?
    options.SignIn.RequireConfirmedPhoneNumber = false;
})
.AddEntityFrameworkStores<AppDbContext>()  // Identity verilerini AppDbContext ile kaydet
.AddDefaultTokenProviders();               // Þifre sýfýrlama, e-posta doðrulama token'larý için

// ???????????????????????????????????????????????????????????????
// 3. COOKÝE (OTURUM ÇEREZÝ) AYARLARI
// ???????????????????????????????????????????????????????????????
// Cookie = Tarayýcýda saklanan küçük bir veri parçasý
// Kullanýcý giriþ yaptýðýnda, tarayýcýsýna bir cookie yerleþtiriyoruz
// Sonraki isteklerde bu cookie ile "bu kullanýcý giriþ yapmýþ" diyoruz
builder.Services.ConfigureApplicationCookie(options =>
{
    // ?????????????????????????????????????????????????????????
    // TEMEL COOKÝE AYARLARI
    // ?????????????????????????????????????????????????????????

    // Cookie'nin adý (tarayýcýda bu isimle görünür)
    options.Cookie.Name = "IncirDesign.Auth";

    // Cookie sadece HTTP isteklerinde gönderilsin
    // JavaScript ile eriþilemesin (XSS saldýrýlarýna karþý koruma)
    options.Cookie.HttpOnly = true;

    // Cookie ne kadar süre geçerli olsun?
    // 60 dakika sonra otomatik çýkýþ yapýlýr
    options.ExpireTimeSpan = TimeSpan.FromMinutes(60);

    // Kullanýcý aktifken süre uzatýlsýn mý?
    // true = Her istekte süre sýfýrlanýr
    options.SlidingExpiration = true;

    // Cookie güvenlik seviyesi
    // Strict = Cookie sadece ayný siteden gelen isteklerde gönderilir
    options.Cookie.SameSite = SameSiteMode.Strict;

    // ?????????????????????????????????????????????????????????
    // YÖNLENDÝRME AYARLARI (Çok Önemli!)
    // ?????????????????????????????????????????????????????????

    // Giriþ yapmamýþ kullanýcý korumalý sayfaya gitmeye çalýþýrsa
    // nereye yönlendirilsin?
    options.LoginPath = "/Account/Login";

    // Çýkýþ yaptýktan sonra nereye yönlendirilsin?
    options.LogoutPath = "/Account/Logout";

    // Giriþ yapmýþ ama yetkisi olmayan kullanýcý nereye yönlendirilsin?
    // Örn: Üye kullanýcý Admin sayfasýna gitmeye çalýþýrsa
    options.AccessDeniedPath = "/Account/AccessDenied";
});

// ???????????????????????????????????????????????????????????????
// 4. MVC SERVÝSLERÝNÝN KAYDI
// ???????????????????????????????????????????????????????????????
builder.Services.AddControllersWithViews();

var app = builder.Build();

// ???????????????????????????????????????????????????????????????
// 5. MIDDLEWARE (ARA YAZILIM) SIRASI
// ???????????????????????????????????????????????????????????????
// Middleware = Ýstek ve yanýt arasýnda çalýþan kod parçalarý
// SIRA ÇOK ÖNEMLÝ! Yanlýþ sýra = Sistem düzgün çalýþmaz

if (!app.Environment.IsDevelopment())
{
    app.UseExceptionHandler("/Home/Error");
    app.UseHsts();
}

app.UseHttpsRedirection();  // HTTP isteklerini HTTPS'e yönlendir
app.UseStaticFiles();       // wwwroot klasöründeki dosyalarý sun (CSS, JS, resimler)
app.UseRouting();           // URL yönlendirmesini aktif et

// ÖNEMLÝ: Authentication MUTLAKA Authorization'dan ÖNCE gelmeli!
// Önce "Kim bu kullanýcý?" sonra "Bu kullanýcý bunu yapabilir mi?"
app.UseAuthentication();    // Kimlik doðrulama
app.UseAuthorization();     // Yetkilendirme
app.UseSession();

app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");

// ???????????????????????????????????????????????????????????????
// 6. VERÝTABANI SEED ÝÞLEMÝ
// ???????????????????????????????????????????????????????????????
// Uygulama baþladýðýnda rolleri ve admin kullanýcýsýný oluþtur
using (var scope = app.Services.CreateScope())
{
    var services = scope.ServiceProvider;
    try
   {
        await DataSeeder.SeedAllAsync(services);
    }
    catch (Exception ex)
    {
        var logger = services.GetRequiredService<ILogger<Program>>();
        logger.LogError(ex, "Seed iþlemi sýrasýnda bir hata oluþtu.");
    }
}

app.Run();
